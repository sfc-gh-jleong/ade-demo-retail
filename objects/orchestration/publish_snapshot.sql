CREATE OR ALTER TASK {{DB}}.ORCHESTRATION.PUBLISH_SNAPSHOT
  WAREHOUSE = COMPUTE_WH
  COMMENT = 'Publishes a revenue snapshot for the finance dashboard'
  AFTER {{DB}}.ORCHESTRATION.BUILD_DAILY_REVENUE
AS
  INSERT INTO {{DB}}.MART.REVENUE_SNAPSHOTS (SNAPSHOT_AT, DAYS, ORDERS, REVENUE_USD)
  SELECT SYSDATE(), COUNT(DISTINCT ORDER_DATE), SUM(ORDERS), SUM(REVENUE_USD)
  FROM {{DB}}.MART.DAILY_REVENUE;
